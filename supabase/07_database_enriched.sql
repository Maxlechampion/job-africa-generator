-- 11. ROW LEVEL SECURITY
-- ============================================================
alter table public.sources enable row level security;
drop policy if exists "sources_public_read" on public.sources;
create policy "sources_public_read"
    on public.sources for select to anon, authenticated using (true);

alter table public.companies enable row level security;
drop policy if exists "companies_public_read" on public.companies;
create policy "companies_public_read"
    on public.companies for select to anon, authenticated using (true);

alter table public.skills enable row level security;
drop policy if exists "skills_public_read" on public.skills;
create policy "skills_public_read"
    on public.skills for select to anon, authenticated using (true);

alter table public.job_skills enable row level security;
drop policy if exists "job_skills_public_read" on public.job_skills;
create policy "job_skills_public_read"
    on public.job_skills for select to anon, authenticated using (true);

alter table public.users enable row level security;
drop policy if exists "users_self_all" on public.users;
create policy "users_self_all"
    on public.users for all to authenticated
    using (auth.uid() = id)
    with check (auth.uid() = id);

alter table public.favorites enable row level security;
drop policy if exists "favorites_self_all" on public.favorites;
create policy "favorites_self_all"
    on public.favorites for all to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

alter table public.alerts enable row level security;
drop policy if exists "alerts_self_all" on public.alerts;
create policy "alerts_self_all"
    on public.alerts for all to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

alter table public.alert_notifications enable row level security;
drop policy if exists "notif_self_read" on public.alert_notifications;
create policy "notif_self_read"
    on public.alert_notifications for select to authenticated
    using (
        exists (
            select 1 from public.alerts a
            where a.id = alert_notifications.alert_id
            and a.user_id = auth.uid()
        )
    );


