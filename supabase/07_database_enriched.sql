-- 12. VUES STATISTIQUES
-- ============================================================
create or replace view public.v_stats_pays as
select
    pays,
    count(*) as total_offres,
    count(distinct company_id) as total_entreprises
from public.jobs
where pays is not null
group by pays
order by total_offres desc;

create or replace view public.v_top_skills as
select
    s.id,
    s.nom,
    s.categorie,
    count(js.job_id) as total_offres
from public.skills s
left join public.job_skills js on js.skill_id = s.id
group by s.id, s.nom, s.categorie
order by total_offres desc;


