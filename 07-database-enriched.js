function patchMainPy() {
  const mainPath = "backend/app/main.py";
  const fullPath = path.join(ROOT, mainPath);

  if (!fs.existsSync(fullPath)) {
    log.error(`Fichier ${mainPath} introuvable`);
    return false;
  }

  let content = fs.readFileSync(fullPath, "utf8");

  if (content.includes("companies")) {
    log.info("main.py deja patche");
    return true;
  }

  try {
    const timestamp = new Date().toISOString().replace(/[:.]/g, "-");
    const backupDir = path.join(ROOT, "_backups", timestamp, "backend", "app");
    fs.mkdirSync(backupDir, { recursive: true });
    fs.copyFileSync(fullPath, path.join(backupDir, "main.py"));
  } catch (e) {
    log.warn(`Backup impossible : ${e.message}`);
  }

  let modified = false;

  // Import
  const importRegex = /from app\.api import ([^\n]+)/;
  const match = content.match(importRegex);

  if (match) {
    const currentImports = match[1];
    const newImports = currentImports + ", companies, skills, favorites, alerts, admin_sources";

    content = content.replace(
      importRegex,
      `from app.api import ${newImports}`
    );
    modified = true;
  }

  // Include routers
  const lastInclude = /app\.include_router\((\w+)\.router\)(?!\napp\.include_router)/g;
  const includes = content.match(lastInclude);

  if (includes && includes.length > 0) {
    const lastIncludeStr = includes[includes.length - 1];

    content = content.replace(
      lastIncludeStr,
      lastIncludeStr +
      "\napp.include_router(companies.router)" +
      "\napp.include_router(skills.router)" +
      "\napp.include_router(favorites.router)" +
      "\napp.include_router(alerts.router)" +
      "\napp.include_router(admin_sources.router)"
    );
    modified = true;
  }

  if (modified && !OPTIONS.dryRun) {
    fs.writeFileSync(fullPath, content, "utf8");
    log.file(mainPath + " (patché)", "overwritten");
  }

  return modified;
}

